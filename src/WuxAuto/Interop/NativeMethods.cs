    /// <summary>Synthetic ALT tap; lifting the foreground lock so the next SetForegroundWindow works.</summary>
    public static void PressAlt()
    {
        const byte VkMenu = 0x12;
        const uint KeyUp = 0x0002;
        keybd_event(VkMenu, 0, 0, UIntPtr.Zero);
        Thread.Sleep(15);
        keybd_event(VkMenu, 0, KeyUp, UIntPtr.Zero);
    }

